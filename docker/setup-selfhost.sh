#!/bin/sh
# Generate docker/.env for a self-hosted Keepsake deployment.
#
# Both the app and the Meilisearch container read MEILI_MASTER_KEY from this
# one file, so the two agree by construction. Setting them independently is how
# search silently broke before: the container ran on one key, the app presented
# another, and every query failed with "The provided API key is invalid" while
# the UI just showed no results.
#
# Usage: ./setup-selfhost.sh <host>
#   e.g. ./setup-selfhost.sh 192.168.1.42
#        ./setup-selfhost.sh keepsake.example.com

set -eu

ENV_FILE="$(cd "$(dirname "$0")" && pwd)/.env"

if [ $# -lt 1 ]; then
    echo "usage: $0 <host-or-ip> [port]" >&2
    echo "  the host is what a browser types to reach this server" >&2
    exit 1
fi

HOST="$1"
PORT="${2:-3000}"

# Sign-in redirects resolve against NEXTAUTH_URL. If it doesn't match the
# address the browser actually used, login bounces back to /signin.
case "$HOST" in
    http://*|https://*) NEXTAUTH_URL="$HOST" ;;
    *)                  NEXTAUTH_URL="http://${HOST}:${PORT}" ;;
esac

if [ -e "$ENV_FILE" ]; then
    echo "refusing to overwrite $ENV_FILE" >&2
    echo "its secrets are the only copy — move it aside first if you mean to regenerate" >&2
    exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl not found; install it or write $ENV_FILE by hand" >&2
    exit 1
fi

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by setup-selfhost.sh on $(date -u '+%Y-%m-%d %H:%M UTC')
# Contains secrets. Never commit (docker/.env is gitignored).

DATA_DIR=/data

# Read by both the web app and the meilisearch container. Keep them equal.
MEILI_MASTER_KEY=$(openssl rand -base64 36 | tr -dc 'A-Za-z0-9')

# Must match the address the browser uses, scheme and port included.
# Put a reverse proxy in front? Set this to the public https:// URL.
NEXTAUTH_URL=$NEXTAUTH_URL
NEXTAUTH_SECRET=$(openssl rand -base64 36)
EOF

echo "wrote $ENV_FILE"
echo "  NEXTAUTH_URL=$NEXTAUTH_URL"
echo
echo "next: docker compose -f $(dirname "$0")/docker-compose.yml up -d"
